import type {
  ArgusHazardDomain,
  ArgusKnowledgeInputType,
  ArgusKnowledgeLicenseType,
  ArgusKnowledgeSource,
  ArgusKnowledgeSourceKind,
  ArgusKnowledgeSourceStatus,
  ArgusSourceReliabilityScore,
} from "@/types/knowledgeIntake";

function reliability(finalScore: number): ArgusSourceReliabilityScore {
  return {
    authorityScore: finalScore,
    freshnessScore: Math.max(40, finalScore - 8),
    technicalDepthScore: Math.max(45, finalScore - 5),
    historicalAccuracyScore: Math.max(45, finalScore - 6),
    geospatialPrecisionScore: Math.max(35, finalScore - 12),
    licenseClarityScore: Math.max(35, finalScore - 10),
    updateCadenceScore: Math.max(35, finalScore - 14),
    biasRiskScore: Math.max(0, 100 - finalScore),
    finalScore,
    label:
      finalScore >= 90
        ? "official_priority"
        : finalScore >= 75
          ? "trusted_secondary"
          : finalScore >= 60
            ? "needs_validation"
            : finalScore >= 40
              ? "context_only"
              : "not_operational",
  };
}

function source(input: {
  id: string;
  name: string;
  description: string;
  status: ArgusKnowledgeSourceStatus;
  sourceKinds: ArgusKnowledgeSourceKind[];
  domains: ArgusHazardDomain[];
  inputTypes: ArgusKnowledgeInputType[];
  accessMethod: ArgusKnowledgeSource["accessMethod"];
  score: number;
  licenseType: ArgusKnowledgeLicenseType;
  licenseNotes: string;
  baseUrl?: string;
  countries?: string[];
  global?: boolean;
  updateCadence?: string;
  integrationNotes?: string;
  tags?: string[];
}): ArgusKnowledgeSource {
  return {
    id: input.id,
    name: input.name,
    description: input.description,
    status: input.status,
    sourceKinds: input.sourceKinds,
    domains: input.domains,
    inputTypes: input.inputTypes,
    accessMethod: input.accessMethod,
    baseUrl: input.baseUrl,
    coverage: {
      countries: input.countries,
      global: input.global ?? !input.countries?.length,
      notes: input.countries?.length ? "Cobertura local/regional declarada." : "Cobertura global o multinacional.",
    },
    reliabilityScore: reliability(input.score),
    licenseType: input.licenseType,
    licenseNotes: input.licenseNotes,
    updateCadence: input.updateCadence,
    integrationNotes: input.integrationNotes ?? "Registered for future Knowledge Intake processing.",
    tags: input.tags ?? [],
  };
}

